OPTIONS = {"class": {"members": "", "undoc-members": "", "show-inheritance": ""}}


@dataclass(frozen=True)
class ApidocOptions:
    """Options of ``generate``. The command line sets ``output_dir``,
    ``force``, ``dry_run``, ``separate`` and ``templatedir``; a script can set
    them all.
    """

    output_dir: str
    force: bool = False
    dry_run: bool = False
    separate: bool = False
    maxdepth: int = 4
    tocfile: str = "index"
    suffix: str = "rst"
    templatedir: str | None = None
    remove_old: bool = True
    group: str = "namespace"
    page_size: int = 100
    #: list ``private/`` files
    private: bool = False


@dataclass
class Page:
    """One output page: its docname, template and template context."""

    docname: str
    template: str
    context: dict


@dataclass
class Result:
    """What ``generate`` wrote (or would write), as paths relative to the
    output folder with ``/``.
    """

    pages: list = field(default_factory=list)
    created: list = field(default_factory=list)
    updated: list = field(default_factory=list)
    unchanged: list = field(default_factory=list)
    kept: list = field(default_factory=list)
    removed: list = field(default_factory=list)
    #: existing files and folders given the case of a page's name
    renamed: list = field(default_factory=list)

    @property
    def changed(self):
        """True if a file was (or would be) created, rewritten, renamed or
        removed.
        """
        return bool(self.created or self.updated or self.removed or self.renamed)


def _warn(message):
    logger.warning("[scmd apidoc] %s", message, type="mat", subtype="apidoc")


def page_folder(reference):
    """Folder reference of the page that lists a file: its folder, or the
    folder above its first ``@`` folder.
    """
    parts = split_folder(folder_of(reference))
    cut = next((i for i, part in enumerate(parts) if part[:1] == "@"), len(parts))
    return join_folder(parts[:cut])


def class_folder_methods(source_index):
    """Return the references of the function files that are methods: those
    of a class folder ``@X/`` whose ``X.m`` is a classdef
    (``mat_types.class_file_reference``, as ``_load_class_folder``).
    """
    types = {r["reference"]: r["type"] for r in source_index.index.values()}
    methods = set()
    for ref, entity in source_index.entities.items():
        if not ref.rstrip("/").rpartition("/")[2].startswith("@"):
            continue
        if types.get(class_file_reference(ref)) != "class":
            continue
        files = [r for _, r in entity.members if r[-1:] != "/" and r in types]
        methods.update(r for r in files if types[r] == "function")
    return methods


def _entry(path, record):
    """Template context of one listed file, or None (with a warning) for a
    file that is skipped.
    """
    ref, kind = record["reference"], record["type"]
    if is_hidden(ref):
        return None
    if kind == UNKNOWN:
        _warn(f"{ref} could not be read; it is left out.")
        return None
    handler = handler_by_extension(path)
    directive = handler.document(kind) if handler is not None else None
    if directive is None:
        _warn(f"{ref}: no directive documents a {kind}; it is left out.")
        return None
    matlab_name = record.get("matlab_name")
    display = matlab_name or ref
    return {
        "ref": ref,
        "kind": kind,
        "directive": directive,
        "argument": ref,
        "options": dict(OPTIONS.get(kind, {})),
        "title": display,
        "display": display,
        "matlab_name": matlab_name,
        "callable": matlab_name is not None,
        "private": bool(record.get("private")),
        "docname": None,
    }


def _entries(path, record):
    """Template contexts of a file: its entry and, for a Simulink library,
    one per masked block (the library is read for them).
    """
    entry = _entry(path, record)
    if entry is None:
        return []
    if entry["kind"] != "library":
        return [entry]
    try:
        blocks = mat_simulink.read_diagram(path).library_blocks
    except (OSError, mat_simulink.SimulinkFileError) as err:
        _warn(f"{entry['ref']}: its blocks cannot be read ({err}); they are left out.")
        return [entry]
    found = [entry]
    for block in blocks:
        if block.mask is None:
            continue
        ref = f"{entry['ref']}/{block.path}"
        name = f"{entry['matlab_name']}/{block.path}" if entry["callable"] else None
        display = " ".join((name or ref).split())
        found.append(
            {
                **entry,
                "ref": ref,
                "kind": "library_block",
                "directive": "mat:autosimulink_library_block",
                # a newline in a block name continues the argument
                "argument": ref.replace("\n", "\n   "),
                "options": {},
                "title": display,
                "display": display,
                "matlab_name": name,
            }
        )
    return found


def _order(entry):
    return entry["title"].casefold(), entry["ref"]


def _sections(entries, order=tuple(SECTIONS)):
    """``(title, entries)`` pairs in page order; entries sorted."""
    entries = sorted(entries, key=_order)
    kinds = {e["kind"] for e in entries}
    order = [*order, *sorted(kinds - set(order))]
    return [
        (SECTIONS.get(kind, kind.title()), [e for e in entries if e["kind"] == kind])
        for kind in order
        if kind in kinds
    ]


def _namespace(source_index, folder):
    """MATLAB name of a ``+`` folder, else None."""
    return getattr(source_index.entities.get(folder), "matlab_name", None)


def _relative(docname, page_docname):
    """``docname`` relative to the folder of the page ``page_docname``."""
    base = posixpath.dirname(page_docname)
    return docname[len(base) + 1 :] if base else docname


def stub_reference(ref):
    """Return the reference whose output name is the page of the sidecar doc
    ``ref``: ``a/guide.md`` -> ``a/guide-md``. Suffixes have no ``-``, so
    names stay distinct; a name that kept the suffix (``guide.md.rst``)
    would lose it in a toctree.
    """
    stem, suffix = posixpath.splitext(ref)
    return f"{stem}-{suffix[1:]}"


def _sidecars(source_index):
    """``(sidecars, readmes)``: the sidecar doc entries (without docnames) by
    the folder whose page lists them, and the README reference by folder.
    """
    by_folder = {}
    for record in source_index.sidecars.values():
        ref = record["reference"]
        name = ref.rpartition("/")[2]
        entry = {"ref": ref, "name": name, "docname": None}
        by_folder.setdefault(page_folder(ref), []).append(entry)
    sidecars, readmes = {}, {}
    for folder, entries in by_folder.items():
        entries.sort(key=lambda e: (e["name"].casefold(), e["ref"]))
        for entry in entries:
            ref = entry["ref"]
            readme = posixpath.splitext(entry["name"])[0].casefold() == "readme"
            if readme and folder_of(ref) == folder and folder not in readmes:
                readmes[folder] = ref
            else:
                sidecars.setdefault(folder, []).append(entry)
    return sidecars, readmes


def build_pages(source_index, options):
    """Return the pages of ``source_index``, sorted by docname: namespace
    pages and the root page, or folder pages in tree order; then object pages
    with ``separate``.
    """
    if options.group == "folder":
        return _folder_pages(source_index, options)
    return _namespace_pages(source_index, options)


def _folder_key(folder):
    """Root folder first, then by path, ignoring case."""
    return (
        folder != ROOT_REFERENCE,
        [s.casefold() for s in split_folder(folder)],
        folder,
    )


def _folder_pages(source_index, options):
    methods = class_folder_methods(source_index)
    private = options.private
    listed = {}
    for path, record in source_index.index.items():
        if record["reference"] in methods or (record.get("private") and not private):
            continue
        for entry in _entries(path, record):
            listed.setdefault(page_folder(record["reference"]), []).append(entry)
    sidecars, readmes = _sidecars(source_index)
    folders = {*listed, *sidecars, *readmes}
    if not folders:
        _warn("no documentable files were found.")

    refs = folders - {ROOT_REFERENCE}
    if options.separate:
        refs.update(e["ref"] for entries in listed.values() for e in entries)
    stubs = {
        e["ref"]: stub_reference(e["ref"])
        for entries in sidecars.values()
        for e in entries
    }
    refs.update(stubs.values())
    names, collisions = docnames(refs, options.suffix, options.tocfile)
    for folder, members in collisions:
        _warn(
            f"the output names of {', '.join(members)} in "
            f"{folder or 'the output folder'}/ are equal or differ only by case; "
            "conflicting characters are escaped as ~XX."
        )
    # Other top-level names are folders (``x/index``) or have a suffix.
    names[ROOT_REFERENCE] = ROOT_FOLDER_DOCNAME
    if options.tocfile.lower() == ROOT_FOLDER_DOCNAME:
        names[ROOT_REFERENCE] = f"~{ord('r'):02X}oot"

    size = max(options.page_size, 1)
    pages_out, toc = [], []
    for folder in sorted(folders, key=_folder_key):
        namespace = _namespace(source_index, folder)
        if folder == ROOT_REFERENCE:
            kind = "root"
        else:
            kind = "namespace" if namespace else "folder"
        # By path: one namespace may span several folders.
        title = f"folder {folder}"
        entries = [
            e for _, section in _sections(listed.get(folder, ())) for e in section
        ]
        items = [*entries, *sidecars.get(folder, [])]
        chunks = [items[i : i + size] for i in range(0, len(items), size)] or [[]]
        for number, chunk in enumerate(chunks, 1):
            docname = names[folder] if number == 1 else f"{names[folder]}-{number}"
            first = (number - 1) * size + 1
            last = first + len(chunk) - 1
            page_entries = [e for e in chunk if "directive" in e]
            page_sidecars = [e for e in chunk if "directive" not in e]
            if options.separate:
                for entry in page_entries:
                    own = names[entry["ref"]]
                    entry["docname"] = _relative(own, docname)
                    pages_out.append(
                        Page(own, OBJECT_TEMPLATE, {**entry, "docname": own})
                    )
            for entry in page_sidecars:
                own = names[stubs[entry["ref"]]]
                entry["docname"] = _relative(own, docname)
                pages_out.append(Page(own, SIDECAR_TEMPLATE, {**entry, "docname": own}))
            pages_out.append(
                Page(
                    docname,
                    FOLDER_TEMPLATE,
                    {
                        "docname": docname,
                        "ref": folder,
                        "title": title
                        if len(chunks) == 1
                        else f"{title} ({first}-{last})",
                        "kind": kind,
                        "is_root": folder == ROOT_REFERENCE,
                        "page": number,
                        "pages": len(chunks),
                        "first": first,
                        "last": last,
                        "sections": _sections(page_entries),
                        "separate": options.separate,
                        "maxdepth": options.maxdepth,
                        "sidecars": page_sidecars,
                        "readme": readmes.get(folder) if number == 1 else None,
                    },
                )
            )
            toc.append(docname)
    pages_out.append(
        Page(
            options.tocfile,
            ROOT_TEMPLATE,
            {
                "docname": options.tocfile,
                "title": ROOT_TITLE,
                "pages": toc,
                "maxdepth": options.maxdepth,
            },
        )
    )
    return sorted(pages_out, key=lambda page: page.docname)


def _group_of(source_index, folder):
    """Return the namespace a page folder belongs to (its MATLAB name), or
    None for the global namespace. A sidecar doc in ``private/`` goes with
    the folder above it.
    """
    parts = split_folder(folder)
    while parts and parts[-1] == "private":
        parts.pop()
    return _namespace(source_index, join_folder(parts))


def _untangle_titles(entries, namespace):
    """Title by path the entries whose MATLAB name another entry of the same
    page group has (path shadowing), with a warning (the blocks of such
    libraries follow them without one).
    """
    by_title = {}
    for entry in entries:
        by_title.setdefault(entry["title"], []).append(entry)
    for title, same in sorted(by_title.items()):
        if len(same) < 2:
            continue
        if same[0]["kind"] != "library_block":
            refs = sorted(e["ref"] for e in same)
            where = f"namespace {namespace}" if namespace else GLOBAL_TITLE
            _warn(
                f"{title} is defined by several files in {where}: "
                f"{', '.join(refs)}; they are listed by path."
            )
        for entry in same:
            entry["title"] = entry["display"] = " ".join(entry["ref"].split())


def _namespace_docnames(namespaces, options, taken):
    """Docname base of each namespace (None: the global namespace); names
    that differ only by case, or that equal the toc file or a name in
    ``taken`` (lowercase), get escaped.
    """
    bases = {
        ns: GLOBAL_DOCNAME if ns is None else escape_segment(ns) for ns in namespaces
    }
    lower = {}
    for ns, base in bases.items():
        lower.setdefault(base.lower(), []).append(ns)
    for group in lower.values():
        if len(group) > 1:
            for ns in group:
                bases[ns] = escape_upper(bases[ns])
    reserved = {options.tocfile.lower(), *taken}
    for ns, base in bases.items():
        if base.lower() in reserved:
            bases[ns] = f"~{ord(base[0]):02X}{base[1:]}"
    return bases


def _namespace_pages(source_index, options):
    methods = class_folder_methods(source_index)
    private = options.private
    groups = {}
    for path, record in source_index.index.items():
        if record["reference"] in methods or (record.get("private") and not private):
            continue
        group = _group_of(source_index, page_folder(record["reference"]))
        for entry in _entries(path, record):
            groups.setdefault(group, ([], []))[0].append(entry)
    for record in source_index.sidecars.values():
        ref = record["reference"]
        group = _group_of(source_index, page_folder(ref))
        entry = {"ref": ref, "name": ref.rpartition("/")[2], "docname": None}
        groups.setdefault(group, ([], []))[1].append(entry)
    if not groups:
        _warn("no documentable files were found.")

    file_names = {}
    if options.separate:
        refs = [e["ref"] for entries, _ in groups.values() for e in entries]
        file_names, _ = docnames(refs, options.suffix, options.tocfile)
    taken = {name.lower() for name in file_names.values()}
    bases = _namespace_docnames(groups, options, taken)
    order = sorted(
        groups, key=lambda ns: (ns is not None, (ns or "").casefold(), ns or "")
    )

    pages_out, toc = [], []
    for ns in order:
        entries, sidecars = groups[ns]
        _untangle_titles(entries, ns)
        flat = [
            e for _, section in _sections(entries, NAMESPACE_ORDER) for e in section
        ]
        sidecars.sort(key=lambda e: (e["name"].casefold(), e["ref"]))
        items = [*flat, *sidecars]
        size = max(options.page_size, 1)
        chunks = [items[i : i + size] for i in range(0, len(items), size)]
        title = GLOBAL_TITLE if ns is None else f"namespace {ns}"
        for number, chunk in enumerate(chunks, 1):
            docname = bases[ns] if number == 1 else f"{bases[ns]}-{number}"
            first = (number - 1) * size + 1
            last = first + len(chunk) - 1
            page_title = title if len(chunks) == 1 else f"{title} ({first}-{last})"
            page_entries = [e for e in chunk if "directive" in e]
            page_sidecars = [e for e in chunk if "directive" not in e]
            sections = _sections(page_entries, NAMESPACE_ORDER)
            if options.separate:
                for entry in page_entries:
                    own = file_names[entry["ref"]]
                    entry["docname"] = own
                    pages_out.append(Page(own, OBJECT_TEMPLATE, dict(entry)))
            pages_out.append(
                Page(
                    docname,
                    NAMESPACE_TEMPLATE,
                    {
                        "docname": docname,
                        "title": page_title,
                        "namespace": ns,
                        "kind": "global" if ns is None else "namespace",
                        "page": number,
                        "pages": len(chunks),
                        "first": first,
                        "last": last,
                        "sections": sections,
                        "sidecars": page_sidecars,
                        "separate": options.separate,
                        "maxdepth": options.maxdepth,
                    },
                )
            )
            toc.append(docname)
    pages_out.append(
        Page(
            options.tocfile,
            ROOT_TEMPLATE,
            {
                "docname": options.tocfile,
                "title": ROOT_TITLE,
                "pages": toc,
                "maxdepth": options.maxdepth,
            },
        )
    )
    return sorted(pages_out, key=lambda page: page.docname)


def render(pages, templatedir=None):
    """Return ``{docname: text}``: each page rendered, after ``MARKER``."""
    path = [templatedir, TEMPLATE_DIR] if templatedir else [TEMPLATE_DIR]
    renderer = ReSTRenderer(path)
    out = {}
    for page in pages:
        text = renderer.render(page.template, page.context).strip("\n")
        out[page.docname] = f"{MARKER}\n\n{text}\n"
    return out


def _is_marked(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.readline().rstrip("\r\n") == MARKER
    except OSError:
        return False


def _starts_with_marker(data):
    return data.split(b"\n", 1)[0].rstrip(b"\r") == MARKER.encode("utf-8")


def _file_id(path):
    """``(st_dev, st_ino)`` of an existing file, or None (no file, or a file
    system without file ids).
    """
    try:
        st = os.stat(path)
    except OSError:
        return None
    return (st.st_dev, st.st_ino) if st.st_ino else None


def _stale(output_dir, suffix, keep_paths, keep_ids):
    """Yield the marked files with ``suffix`` below ``output_dir`` that are not
    pages of this run. A file is a page if it is the same file as one (its
    ``_file_id`` is in ``keep_ids``), so the case of its name does not matter;
    without a file id, if its normalized path is in ``keep_paths``. Folders
    starting with ``.`` or ``_`` hold no pages and are not searched.
    """
    for dirpath, dirnames, filenames in os.walk(output_dir):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith((".", "_")))
        for name in sorted(filenames):
            path = os.path.join(dirpath, name)
            if not name.endswith(f".{suffix}"):
                continue
            file_id = _file_id(path)
            if file_id is None:
                current = os.path.normcase(path) in keep_paths
            else:
                current = file_id in keep_ids
            if not current and _is_marked(path):
                yield path


def _remove_empty(folder, output_dir):
    """Remove ``folder`` and the folders above it up to ``output_dir`` while
    they are empty.
    """
    top = os.path.normcase(output_dir)
    while os.path.normcase(folder) != top and folder.startswith(output_dir):
        try:
            os.rmdir(folder)
        except OSError:
            return
        folder = os.path.dirname(folder)


def _same_file(a, b):
    try:
        return os.path.samefile(a, b)
    except OSError:
        return False


def _match_case(output_dir, parts, options, listings, renamed):
    """On a case-insensitive file system, give the existing folders and file
    of the page ``parts`` (below ``output_dir``) the case of its name, so a
    case-only rename of a source reaches the output; each one is added to
    ``renamed``. Return False if the file exists under another case without
    the marker and ``options.force`` is off (it is kept). ``listings``
    caches ``(names, by casefold)`` per folder for one run; it does not see
    files and folders this run creates, so a name counts as another case of
    ``part`` only if both name the same file.
    """
    folder = output_dir
    for i, part in enumerate(parts):
        if folder not in listings:
            try:
                names = os.listdir(folder)
            except OSError:
                listings[folder] = None
            else:
                listings[folder] = (set(names), {n.casefold(): n for n in names})
        if listings[folder] is None:
            return True
        names, folded = listings[folder]
        target = os.path.join(folder, part)
        current = None if part in names else folded.get(part.casefold())
        old = None if current is None else os.path.join(folder, current)
        if old is not None and _same_file(old, target):
            last = i == len(parts) - 1
            if last and not options.force and not _is_marked(old):
                _warn(
                    f"{old} has no marker line and its name differs from "
                    f"{part} only by case; it is kept (-f overwrites it)."
                )
                return False
            renamed_part = "/".join(parts[: i + 1])
            # a dry run keeps the old name, so later pages meet it again
            if renamed_part not in renamed:
                renamed.append(renamed_part)
            if not options.dry_run:
                os.rename(old, target)
                names.discard(current)
                names.add(part)
                folded[part.casefold()] = part
        folder = target
    return True


def generate(source_index, options):
    """Write the pages of ``source_index`` below ``options.output_dir``.

    Returns a ``Result``. A page that exists with other text is rewritten
    if it starts with ``MARKER`` (or with ``force``), else kept with a
    warning; with ``dry_run`` nothing is written, renamed or removed.
    """
    output_dir = os.path.abspath(options.output_dir)
    pages = build_pages(source_index, options)
    texts = render(pages, options.templatedir)
    result = Result(pages=[page.docname for page in pages])
    keep = set()
    listings = {}
    for docname, text in texts.items():
        rel = f"{docname}.{options.suffix}"
        path = os.path.join(output_dir, *rel.split("/"))
        keep.add(os.path.normcase(path))
        if _WINDOWS and too_long(path):
            _warn(
                f"{path} has {len(path)} characters; Windows allows "
                f"{WINDOWS_MAX_PATH} unless long paths are enabled."
            )
        data = text.encode("utf-8")
        if not _match_case(
            output_dir, rel.split("/"), options, listings, result.renamed
        ):
            result.kept.append(rel)
            continue
        try:
            with open(path, "rb") as f:
                old = f.read()
        except FileNotFoundError:
            status = result.created
        else:
            # A CRLF checkout (git core.autocrlf) is not a change.
            if old == data or old.replace(b"\r\n", b"\n") == data:
                result.unchanged.append(rel)
                continue
            if not options.force and not _starts_with_marker(old):
                _warn(f"{path} has no marker line; it is kept (-f overwrites it).")
                result.kept.append(rel)
                continue
            status = result.updated
        status.append(rel)
        if not options.dry_run:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)

    if options.remove_old and os.path.isdir(output_dir):
        paths = [
            os.path.join(output_dir, *f"{d}.{options.suffix}".split("/")) for d in texts
        ]
        keep_ids = {i for i in map(_file_id, paths) if i is not None}
        for path in list(_stale(output_dir, options.suffix, keep, keep_ids)):
            result.removed.append(Path(os.path.relpath(path, output_dir)).as_posix())
            if not options.dry_run:
                os.remove(path)
                _remove_empty(os.path.dirname(path), output_dir)
    return result
